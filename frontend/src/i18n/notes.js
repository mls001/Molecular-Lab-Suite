// 后端返回的「操作说明」（mol.note）是中文散文，直接显示在切换英文后不会翻译。
// 这里按固定模板把它们还原成 i18n key + 参数，再走统一词典翻译；
// 词典里查不到的片段原样返回，不会丢信息。
import { t, lang } from '@/i18n'

const PATTERNS = [
  [/^已放置(.+?)（(\d+) 个原子）$/, (m) => t('已放置 {0}（{1} 个原子）', { 0: t(m[1]), 1: m[2] })],
  [/^已放置(.+)$/, (m) => t('已放置 {0}', { 0: t(m[1]) })],
  [/^已在原子 (\d+) 上稠合(.+)$/, (m) => t('已在原子 {0} 上稠合 {1}', { 0: m[1], 1: t(m[2]) })],
  [/^已添加 (.+?)（原子序号 (\d+)）$/, (m) => t('已添加 {0}（原子序号 {1}）', { 0: m[1], 1: m[2] })],
  [/^原子 (\d+) 电荷改为 (-?\d+)$/, (m) => t('原子 {0} 电荷改为 {1}', { 0: m[1], 1: m[2] })],
  [/^原子 (\d+) 已改为 (.+)$/, (m) => t('原子 {0} 已改为 {1}', { 0: m[1], 1: m[2] })],
  [/^原子 (\d+) 坐标已更新$/, (m) => t('原子 {0} 坐标已更新', { 0: m[1] })],
  [/^已建立键 (\d+)-(\d+)（键级 (\d+)）$/, (m) => t('已建立键 {0}-{1}（键级 {2}）', { 0: m[1], 1: m[2], 2: m[3] })],
  [/^已删除键 (\d+)-(\d+)$/, (m) => t('已删除键 {0}-{1}', { 0: m[1], 1: m[2] })],
  [/^键 (\d+)-(\d+) 键级改为 (\d+)$/, (m) => t('键 {0}-{1} 键级改为 {2}', { 0: m[1], 1: m[2], 2: m[3] })],
  [/^结构未完全通过净化（(.+)）$/, (m) => t('结构未完全通过净化（{0}）', { 0: m[1] })],
  [/^力场优化跳过（(.+)）$/, (m) => t('力场优化跳过（{0}）', { 0: m[1] })]
]

const PLAIN = [
  '已删除原子（后续原子序号已重排）',
  '已加氢', '已去氢', '已加显式氢', '已去掉显式氢',
  'MMFF94 优化完成', 'UFF 优化完成', '缺少 MMFF 参数，改用 UFF 优化',
  '已用 ETKDG 生成 3D 构象', '已用 ETKDG 生成 3D 构象（未做力场优化）',
  '3D 嵌入失败（可能缺少氢或价键异常），已保留原坐标',
  '已生成 2D 坐标（可直接在 2D 画布上修改）',
  '已从 PubChem 载入（2D 结构，可点「转换为 3D」）'
]

export function tNote(text) {
  if (!text) return ''
  const sep = lang.value === 'en' ? '; ' : '；'
  return String(text).split('；').map((part) => {
    const s = part.trim()
    if (!s) return ''
    for (const [re, fn] of PATTERNS) {
      const m = re.exec(s)
      if (m) return fn(m)
    }
    if (PLAIN.includes(s)) return t(s)
    return s
  }).filter(Boolean).join(sep)
}
